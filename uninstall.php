<?php

// جلوگیری از اجرای مستقیم فایل
if (!defined('WP_UNINSTALL_PLUGIN')) {
    exit;
}

global $wpdb;

/*
|--------------------------------------------------------------------------
| بررسی رضایت صریح مدیر سایت برای حذف داده‌ها
|--------------------------------------------------------------------------
| به‌صورت پیش‌فرض، حذف پلاگین هیچ داده‌ای (سفارش‌های متقاضیان، تنظیمات،
| جدول اعلان‌ها) را پاک نمی‌کند. فقط اگر مدیر سایت از قبل، در صفحه‌ی
| تنظیمات پلاگین، گزینه‌ی «حذف اطلاعات هنگام حذف پلاگین» را فعال کرده
| باشد، این عملیات (که کاملاً غیرقابل‌بازگشت است) انجام می‌شود.
|--------------------------------------------------------------------------
*/

$fd_settings = get_option('formdesk_settings');
$fd_should_delete_data = !empty($fd_settings['delete_data_on_uninstall']);

if (!$fd_should_delete_data) {
    // مدیر سایت اجازه‌ی حذف داده‌ها را نداده: فقط از اجرای ادامه‌ی فایل صرف‌نظر می‌کنیم
    return;
}

/*
|--------------------------------------------------------------------------
| حذف کامل تمام سفارش‌های ثبت‌نام (متقاضیان) ساخته‌شده توسط پلاگین
|--------------------------------------------------------------------------
| توجه: این عملیات غیرقابل‌بازگشت است. تمام اطلاعات متقاضیانی که تا
| این لحظه در سیستم ثبت شده‌اند (شامل سفارش ووکامرس و تمام متاهای آن)
| برای همیشه پاک می‌شوند تا در صورت نصب مجدد پلاگین، امکان ثبت دوباره
| با همان کد ملی / شماره همراه وجود داشته باشد.
|--------------------------------------------------------------------------
*/

if (function_exists('wc_get_orders')) {

    $order_ids = wc_get_orders(array(
        'limit'      => -1,
        'meta_key'   => '_fd_status',
        'return'     => 'ids',
    ));

    foreach ($order_ids as $order_id) {

        $order = wc_get_order($order_id);

        if ($order) {
            $order->delete(true); // حذف کامل و سازگار با HPOS
        }
    }
}

/*
|--------------------------------------------------------------------------
| حذف جدول اعلان‌ها
|--------------------------------------------------------------------------
*/

$table = $wpdb->prefix . 'formdesk_notifications';
$wpdb->query("DROP TABLE IF EXISTS {$table}");

/*
|--------------------------------------------------------------------------
| حذف تمام تنظیمات پلاگین
|--------------------------------------------------------------------------
*/

delete_option('formdesk_settings');
delete_option('formdesk_fields');
delete_option('formdesk_statuses');
delete_option('formdesk_db_version');

/*
|--------------------------------------------------------------------------
| پاک‌سازی کش آبجکت (در صورت فعال بودن افزونه‌های کش)
|--------------------------------------------------------------------------
*/

wp_cache_flush();
